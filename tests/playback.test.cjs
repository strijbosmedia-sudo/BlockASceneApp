const assert=require('node:assert/strict');
const P=require('../app/playback.js'), M=require('../app/model.js');
const project=M.createProject(),beats=project.scenes[0].beats,actor=project.scenes[0].actors[0].id,camera=project.scenes[0].cameras[0].id;
assert.equal(P.duration(3,{speed:1}),9400);
assert.equal(P.duration(3,{speed:2}),4700);
assert.equal(P.frameAt(beats,0,{}).index,0);
assert.equal(P.frameAt(beats,2500,{}).phase,'transition');
assert.equal(P.frameAt(beats,3450,{}).index,1);
assert.equal(P.frameAt(beats,9400,{}).done,true);
assert.equal(P.frameAt(beats,9400,{speed:2}).done,true);
const atHalf=P.frameAt(beats,2975,{speed:1,mode:'move'});
assert.equal(atHalf.phase,'transition');
assert.ok(Math.abs(atHalf.states.positions[actor].x-(beats[0].positions[actor].x+beats[1].positions[actor].x)/2)<.01);
const original=JSON.stringify(beats);
const rotation=P.mixAngle(350,10,.5);
assert.equal(((rotation%360)+360)%360,0);
assert.deepEqual(JSON.stringify(beats),original);
const ghost=P.frameAt(beats,2975,{mode:'ghost'});
assert.equal(ghost.states,null);assert.ok(ghost.fromStates);assert.ok(ghost.toStates);
beats[0].cameras[camera].motion={kind:'push',endX:700,endY:450,endRotation:40};
const moved=P.frameAt(beats,1250,{mode:'move'});
assert.equal(moved.phase,'hold');
assert.ok(moved.states.cameras[camera].x>beats[0].cameras[camera].x);
assert.ok(moved.states.cameras[camera].x<700);
const hidden={...beats[0].positions[actor],visible:false};
assert.equal(P.mixState(hidden,beats[1].positions[actor],.5).alpha,.5);
M.setOutline(project,actor,'black');
assert.equal(project.identities[actor].outline,'black');
assert.equal(M.migrate(project).scenes[0].actors[0].outline,'black');
console.log('Playback and outline tests passed');
