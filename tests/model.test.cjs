const assert=require('node:assert/strict');
const M=require('../app/model.js');
const project=M.createProject('v0.2 Test');
const scene=project.scenes[0];
assert.equal(scene.beats.length,3);
assert.equal(scene.actors.length,2);
assert.equal(scene.cameras.length,2);
assert.equal(new Set([...scene.actors,...scene.cameras].map(e=>e.color.toLowerCase())).size,4);
const actor=scene.actors[0],cam=scene.cameras[0],original=scene.beats[0];
original.positions[actor.id].rotation=22;
original.cameras[cam.id].rotation=30;
const beat=M.nextBeat(scene,original);
assert.equal(beat.positions[actor.id].rotation,22);
assert.equal(beat.cameras[cam.id].rotation,30);
beat.positions[actor.id].x+=300;
assert.notEqual(beat.positions[actor.id].x,original.positions[actor.id].x);
const plus=M.addIdentity(project,scene,'camera',beat,{x:85,y:55});
assert.ok(plus.number>2);
assert.equal(beat.cameras[plus.id].x,85);
assert.equal(original.cameras[plus.id],undefined);
assert.equal(M.recolor(project,plus.id,actor.color),null,'assigned colors may be reused');
for(let i=0;i<35;i++)M.addIdentity(project,scene,'actor',beat,{x:100+i,y:80});
let cols=Object.values(project.identities).map(o=>o.color.toLowerCase());
assert.equal(new Set(cols).size,cols.length-1,'automatic colors remain distinct while the explicit duplicate is retained');
const old={id:'oldproject',name:'old',sets:[{id:'set',name:'Room',objects:[]}],scenes:[{id:'scene',name:'One',setId:'set',actors:[{id:'actor',name:'A',color:'#419fe2'}],setups:[{id:'cam',name:'Master',x:50,y:100,rotation:30,lens:35,sensor:36}],beats:[{id:'b1',name:'Start',positions:{actor:{x:1,y:2}}},{id:'b2',name:'End',positions:{actor:{x:3,y:5}}}]}]};
const migrated=M.migrate(old);
assert.equal(migrated.schemaVersion,2);
assert.equal(migrated.scenes[0].cameras.length,1);
assert.equal(migrated.scenes[0].beats[1].cameras.cam.x,50);
assert.equal(migrated.scenes[0].beats[0].positions.actor.rotation,-90);
assert.ok(migrated.identities.cam?.color);
assert.equal(old.scenes[0].beats[0].cameras,undefined,'migration must not mutate old');
assert.equal(M.migrate(migrated).scenes[0].cameras.length,1,'migration is idempotent');
// Per-beat object visibility, including early beats that did not yet contain the object.
assert.equal(M.PRESET.length%7,0,'the actor/camera color palette fills all 7 columns');
const lateCam=M.addIdentity(project,scene,'camera',beat,{x:400,y:410});
assert.equal(scene.beats[0].cameras[lateCam.id],undefined);
assert.equal(M.setBeatVisibility(scene,'camera',lateCam.id,scene.beats[0].id,true),true);
assert.equal(scene.beats[0].cameras[lateCam.id].visible,true);
assert.equal(scene.beats[0].cameras[lateCam.id].x,400);
assert.equal(M.setBeatVisibility(scene,'camera',lateCam.id,scene.beats[0].id,false),true);
assert.equal(scene.beats[0].cameras[lateCam.id].visible,false);
assert.equal(beat.cameras[lateCam.id].visible,true,'other beats remain unchanged');
assert.equal(M.setBeatVisibility(scene,'camera','bogus',scene.beats[0].id,true),false);
console.log('Model tests passed');
