const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const file=p=>fs.readFileSync(path.join(root,p),'utf8');
const pkg=JSON.parse(file('package.json'));
assert.match(pkg.version,/^1\.(3|4)\.[0-9]+$/);
assert.equal(pkg.author,'strijbos.media');
assert.match(pkg.build.copyright,/strijbos\.media/);
assert.equal(pkg.build.appId,'film.blockascene.app','Windows user data remains compatible');
assert.equal(pkg.build.mac.category,'public.app-category.video');
assert.ok(pkg.scripts['dist:win']&&pkg.scripts['dist:mac']);
assert.match(pkg.scripts['mobile:android'],/cap sync android/);
assert.match(pkg.scripts['mobile:ios'],/cap sync ios/);
for(const v of ['@capacitor/core','@capacitor/filesystem','@capacitor/share'])assert.ok(pkg.dependencies[v]);
const config=JSON.parse(file('capacitor.config.json'));
assert.equal(config.webDir,'mobile/www');
assert.equal(config.appId,'media.strijbos.block4film');
assert.match(file('scripts/prepare-mobile.cjs'),/esbuild\.buildSync/);
assert.match(file('mobile/bridge.js'),/Filesystem\.writeFile/);
assert.match(file('mobile/bridge.js'),/Share\.share/);
assert.match(file('app/app.js'),/Block4FilmMobile\.saveFile/);
assert.match(file('.github/workflows/cross-platform.yml'),/assembleDebug/);
assert.match(file('.github/workflows/cross-platform.yml'),/iphonesimulator/);
assert.match(file('.github/workflows/cross-platform.yml'),/dist:mac/);
assert.match(file('.github/workflows/release.yml'),/WINDOWS_TAG: v1\.(3|4)\.[0-9]+/);
assert.match(file('.github/workflows/release.yml'),/WIN_CSC_LINK/);
assert.doesNotMatch(file('.github/workflows/release.yml'),/WINDOWS_TAG: v1\.2\.1/);
console.log('Block4Film v1.3 portability and strijbos.media release configuration checks passed');
